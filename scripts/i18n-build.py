#!/usr/bin/env python3
"""Build i18n data from JSON files under i18n/ into src/lua/client/pzopt/pzopt_i18n_data.lua.

build.sh runs this alongside option-classes.py and option-dates.py.
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N_DIR = ROOT / "i18n"
OUT = ROOT / "src/lua/shared/pzopt/pzopt_i18n_data.lua"


# The game's Lua lexer (B42 org.luaj.kahluafork.compiler.LexState.save) stores each character of a string
# literal as its single LOW BYTE (char & 0xFF) and re-decodes the buffer as UTF-8, so a raw non-ASCII
# character ("卸" -> 0x78 'x') compiles into mojibake. Every non-ASCII character therefore goes out as
# UTF-8 \ddd byte escapes ("卸" -> "\\229\141\184"), which the lexer saves byte-exact and the UTF-8
# decode rebuilds. Escape sequences of \ddd consume at most 3 following digits, and our sequences are
# always 1-3 digits terminated by another escape, a quote, or plain text, so nothing runs together.
def escape_string(val):
    out = []
    for ch in val:
        o = ord(ch)
        if o < 0x80:
            if ch == "\\":
                out.append("\\\\")
            elif ch == '"':
                out.append('\\"')
            elif ch == "\n":
                out.append("\\n")
            elif ch == "\r":
                out.append("\\r")
            else:
                out.append(ch)
        else:
            for b in ch.encode("utf-8"):
                out.append(f"\\{b:03d}")
    return "".join(out)


def to_lua(val, indent=2):
    sp = " " * indent
    if isinstance(val, dict):
        if not val:
            return "{}"
        lines = ["{\n"]
        for k, v in val.items():
            if k.isidentifier() and not k.startswith("_") and k.isascii():
                key_str = k
            else:
                key_str = f'["{escape_string(k)}"]'
            lines.append(f"{sp}{key_str} = {to_lua(v, indent + 2)},\n")
        lines.append(" " * (indent - 2) + "}")
        return "".join(lines)
    elif isinstance(val, list):
        if not val:
            return "{}"
        lines = ["{\n"]
        for item in val:
            lines.append(f"{sp}{to_lua(item, indent + 2)},\n")
        lines.append(" " * (indent - 2) + "}")
        return "".join(lines)
    elif isinstance(val, str):
        return f'"{escape_string(val)}"'
    elif isinstance(val, bool):
        return "true" if val else "false"
    elif val is None:
        return "nil"
    elif isinstance(val, (int, float)):
        return str(val)
    else:
        return f'"{str(val)}"'


def main():
    if not I18N_DIR.is_dir():
        print(f"[i18n] directory {I18N_DIR} does not exist, creating empty data")
        OUT.write_text("PzoptI18nData = {}\n", encoding="utf-8")
        return

    languages = {}
    for f in sorted(I18N_DIR.glob("*.json")):
        lang_id = f.stem.lower()
        try:
            with open(f, "r", encoding="utf-8") as fp:
                data = json.load(fp)
            languages[lang_id] = data
            opt_count = len(data.get("options", {}))
            print(f"[i18n] loaded {f.name}: {opt_count} options translated")
        except Exception as e:
            print(f"[i18n] ERROR reading {f}: {e}", file=sys.stderr)
            sys.exit(1)

    content = [
        "-- Generated by scripts/i18n-build.py from i18n/*.json. Do not edit directly.\n",
        "PzoptI18nData = " + to_lua(languages, indent=2) + "\n",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(content), encoding="utf-8")
    print(f"[i18n] wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
